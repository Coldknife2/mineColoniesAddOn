package com.coldknife.minergy;

import com.coldknife.minergy.client.MinergyHud;
import com.coldknife.minergy.colony.MinergyBuildingModules;
import com.coldknife.minergy.colony.MinergyJobs;
import com.coldknife.minergy.core.MinergyConfig;
import com.coldknife.minergy.core.MinergyEvents;
import com.coldknife.minergy.core.MinergyManager;
import com.coldknife.minergy.loot.NoDropLootModifier;
import com.coldknife.minergy.marks.ChunkMinergyMarks;
import com.coldknife.minergy.network.MinergyNetwork;
import com.minecolonies.api.IMinecoloniesAPI;
import com.minecolonies.api.colony.jobs.ModJobs;
import com.minecolonies.api.eventbus.events.colony.ColonyDeletedModEvent;
import com.minecolonies.api.sounds.ModSoundEvents;
import com.minecolonies.core.colony.buildings.modules.BuildingModules;
import com.mojang.logging.LogUtils;
import net.minecraft.resources.ResourceLocation;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.common.MinecraftForge;
import net.minecraftforge.common.capabilities.RegisterCapabilitiesEvent;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.fml.DistExecutor;
import net.minecraftforge.fml.ModLoadingContext;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.config.ModConfig;
import net.minecraftforge.fml.event.lifecycle.FMLCommonSetupEvent;
import net.minecraftforge.fml.javafmlmod.FMLJavaModLoadingContext;
import org.slf4j.Logger;

import java.util.Objects;

/**
 * MineColonies add-on: the Minergy, a colony-bound energy generated by the Mystical Mage at the Library,
 * that builders can spend to place blocks they do not have.
 */
@Mod(Minergy.MOD_ID)
public class Minergy
{
    public static final String MOD_ID = "minergy";

    public static final Logger LOGGER = LogUtils.getLogger();

    public Minergy()
    {
        final IEventBus modBus = FMLJavaModLoadingContext.get().getModEventBus();

        ModLoadingContext.get().registerConfig(ModConfig.Type.SERVER, MinergyConfig.SPEC);

        MinergyJobs.JOBS.register(modBus);
        NoDropLootModifier.SERIALIZERS.register(modBus);

        modBus.addListener(this::onRegisterCapabilities);
        modBus.addListener(this::onCommonSetup);

        MinecraftForge.EVENT_BUS.register(new MinergyEvents());
        DistExecutor.unsafeRunWhenOn(Dist.CLIENT, () -> () -> MinecraftForge.EVENT_BUS.register(new MinergyHud()));

        MinergyNetwork.register();
    }

    public static ResourceLocation id(final String path)
    {
        return new ResourceLocation(MOD_ID, path);
    }

    private void onRegisterCapabilities(final RegisterCapabilitiesEvent event)
    {
        event.register(ChunkMinergyMarks.class);
    }

    private void onCommonSetup(final FMLCommonSetupEvent event)
    {
        event.enqueueWork(() -> {
            // MineColonies' own module producers must get their runtime ids before ours, on both sides.
            Objects.requireNonNull(BuildingModules.STATS_MODULE);
            MinergyBuildingModules.attachToLibrary();

            // Citizen sounds are looked up by job path: the mage speaks like the researcher.
            ModSoundEvents.CITIZEN_SOUND_EVENTS.put(MinergyJobs.MYSTICAL_MAGE_ID.getPath(),
                ModSoundEvents.CITIZEN_SOUND_EVENTS.get(ModJobs.RESEARCHER_ID.getPath()));

            IMinecoloniesAPI.getInstance().getEventBus().subscribe(ColonyDeletedModEvent.class, e -> MinergyManager.onColonyDeleted(e.getColony()));

            LOGGER.info("Minergy attached to the Library");
        });
    }
}
