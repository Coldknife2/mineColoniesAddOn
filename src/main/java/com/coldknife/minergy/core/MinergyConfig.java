package com.coldknife.minergy.core;

import net.neoforged.neoforge.common.ModConfigSpec;

/**
 * Server-side configuration (saved per world in serverconfig/minergy-server.toml).
 */
public final class MinergyConfig
{
    public static final ModConfigSpec SPEC;

    public static final ModConfigSpec.IntValue    COST_PER_BLOCK;
    public static final ModConfigSpec.DoubleValue BASE_RATE;
    public static final ModConfigSpec.DoubleValue RATE_PER_LEVEL;
    public static final ModConfigSpec.DoubleValue MAX_SKILL_BONUS;
    public static final ModConfigSpec.DoubleValue RATE_MULTIPLIER;
    public static final ModConfigSpec.LongValue   STORAGE_PER_LEVEL;
    public static final ModConfigSpec.DoubleValue TOWN_HALL_RATE;
    public static final ModConfigSpec.LongValue   BASE_STORAGE;
    public static final ModConfigSpec.IntValue    BOOST_COST_STEP;
    public static final ModConfigSpec.DoubleValue BOOST_BONUS_PER_STEP;
    public static final ModConfigSpec.IntValue    BOOST_DURATION_SECONDS;
    public static final ModConfigSpec.IntValue    BOOST_MAX_STEPS;

    static
    {
        final ModConfigSpec.Builder builder = new ModConfigSpec.Builder();

        builder.comment("Minergy cost of the placements made with Minergy").push("cost");
        COST_PER_BLOCK = builder
            .comment("Minergy consumed by the builder for one block placement without the item in inventory.")
            .defineInRange("costPerBlock", 1, 0, 1_000_000);
        builder.pop();

        builder.comment("Minergy generation by the Mystical Mage, per second of work").push("generation");
        BASE_RATE = builder
            .comment("Minergy per second of a beginner mage at Library level 1.")
            .defineInRange("baseRate", 4.0D, 0.0D, 1_000_000.0D);
        RATE_PER_LEVEL = builder
            .comment("Additional Minergy per second for each Library level above 1.")
            .defineInRange("ratePerLevel", 3.0D, 0.0D, 1_000_000.0D);
        MAX_SKILL_BONUS = builder
            .comment("Bonus ratio granted by a mage with Mana 99 (0.25 = +25%). Scales linearly with the Mana skill.")
            .defineInRange("maxSkillBonus", 0.25D, 0.0D, 100.0D);
        RATE_MULTIPLIER = builder
            .comment("Global multiplier applied to the whole generation.")
            .defineInRange("rateMultiplier", 1.0D, 0.0D, 1000.0D);
        TOWN_HALL_RATE = builder
            .comment("Minergy per second generated by the town hall as soon as it is placed, to kickstart the colony.")
            .defineInRange("townHallRate", 1.0D, 0.0D, 1_000_000.0D);
        builder.pop();

        builder.comment("Minergy storage of a colony").push("storage");
        BASE_STORAGE = builder
            .comment("Minergy a colony can store without any Library (town hall generation).")
            .defineInRange("baseStorage", 10_000L, 0L, Long.MAX_VALUE);
        STORAGE_PER_LEVEL = builder
            .comment("Additional Minergy a colony can store, per level of its best Library. 0 = unlimited storage.")
            .defineInRange("storagePerLevel", 100_000L, 0L, Long.MAX_VALUE);
        builder.pop();

        builder.comment("Speed boosts bought with Minergy for a citizen").push("boost");
        BOOST_COST_STEP = builder
            .comment("Minergy cost of one boost step.")
            .defineInRange("costPerStep", 120, 1, 1_000_000);
        BOOST_BONUS_PER_STEP = builder
            .comment("Speed bonus of one boost step (0.5 = +50% work and movement speed).")
            .defineInRange("bonusPerStep", 0.5D, 0.0D, 100.0D);
        BOOST_DURATION_SECONDS = builder
            .comment("Duration of a boost, in seconds.")
            .defineInRange("durationSeconds", 60, 1, 86_400);
        BOOST_MAX_STEPS = builder
            .comment("Maximum number of steps bought at once.")
            .defineInRange("maxSteps", 10, 1, 1000);
        builder.pop();

        SPEC = builder.build();
    }

    private MinergyConfig()
    {
    }
}
